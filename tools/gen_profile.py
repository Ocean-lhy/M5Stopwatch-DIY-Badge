#!/usr/bin/env python3
"""Turn the badge profile into firmware defaults.

Uses <project>/profile/ when it exists (personal, git-ignored), otherwise the
committed template <project>/profile.example/. Each directory holds:

    profile.json   name, title, QR codes, ... (see profile.example/profile.json)
    avatar.jpg     square JPEG shown by the web editor until a new photo is uploaded

Writes <out>/badge_profile.h and <out>/avatar.jpg, touching them only on change.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

# Byte limits including the terminator, mirroring BadgeConfig in main/badge_config.h.
TEXT_FIELDS = {
    "name": 48, "title": 48, "company": 48, "intro": 200, "seeking": 120,
    "booth": 24, "tags": 96, "email": 64, "phone": 24,
}
QR_LABEL_MAX, QR_TEXT_MAX, QR_SLOTS = 32, 256, 3
THEMES = {"ocean": 0, "brand": 1, "paper": 2}


def c_string(text: str) -> str:
    # Octal escapes are at most three digits, so they never swallow following text.
    out = []
    for b in text.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif b < 0x20 or b >= 0x7F:
            out.append(f"\\{b:03o}")
        else:
            out.append(chr(b))
    return '"' + "".join(out) + '"'


def fail(source: Path, message: str):
    sys.exit(f"gen_profile: {source}: {message}")


def load(source: Path) -> dict:
    path = source / "profile.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as err:
        fail(path, f"cannot read profile ({err})")
    if isinstance(data.get("tags"), list):
        data["tags"] = ",".join(str(t).strip() for t in data["tags"] if str(t).strip())
    for key, limit in TEXT_FIELDS.items():
        value = str(data.get(key, "") or "")
        if len(value.encode("utf-8")) >= limit:
            fail(path, f'"{key}" is {len(value.encode())} bytes, limit is {limit - 1}')
        data[key] = value
    theme = data.get("theme", "ocean")
    if theme not in THEMES:
        fail(path, f'"theme" must be one of {", ".join(THEMES)}')
    data["theme"] = THEMES[theme]
    qr = data.get("qr", [])
    if not isinstance(qr, list) or len(qr) > QR_SLOTS:
        fail(path, f'"qr" must be a list of at most {QR_SLOTS} entries')
    for i, slot in enumerate(qr):
        label, text = str(slot.get("label", "")), str(slot.get("text", ""))
        if not text:
            fail(path, f"qr[{i}].text is empty")
        if len(label.encode()) >= QR_LABEL_MAX or len(text.encode()) >= QR_TEXT_MAX:
            fail(path, f"qr[{i}] label must be < {QR_LABEL_MAX} bytes and text < {QR_TEXT_MAX} bytes")
    data["qr"] = qr
    data["tz"] = int(data.get("timezone_offset_min", 480))
    return data


def write_if_changed(path: Path, content: bytes):
    if not path.exists() or path.read_bytes() != content:
        path.write_bytes(content)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    source = args.project / "profile"
    if not (source / "profile.json").exists():
        source = args.project / "profile.example"
    data = load(source)
    avatar = source / "avatar.jpg"
    if not avatar.exists() or avatar.read_bytes()[:2] != b"\xff\xd8":
        fail(avatar, "missing or not a JPEG")

    lines = [
        "// Generated by tools/gen_profile.py. Edit profile/profile.json instead.",
        "#pragma once",
        "",
        f"#define BADGE_PROFILE_SOURCE {c_string(source.name)}",
        "",
    ]
    for key in TEXT_FIELDS:
        lines.append(f"static constexpr const char kProfile_{key}[] = {c_string(data[key])};")
    lines += [
        f"static constexpr int kProfileTheme = {data['theme']};",
        f"static constexpr int kProfileTzOffsetMin = {data['tz']};",
        f"static constexpr int kProfileQrCount = {len(data['qr'])};",
        "static constexpr const char *kProfileQr[][2] = {",
    ]
    for slot in data["qr"] or [{"label": "", "text": ""}]:
        lines.append(f"    {{{c_string(str(slot.get('label', '')))}, {c_string(str(slot['text']))}}},")
    lines += ["};", ""]

    args.out.mkdir(parents=True, exist_ok=True)
    write_if_changed(args.out / "badge_profile.h", "\n".join(lines).encode())
    write_if_changed(args.out / "avatar.jpg", avatar.read_bytes())
    print(f"gen_profile: using {source.relative_to(args.project)}/")


if __name__ == "__main__":
    main()
