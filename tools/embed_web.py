#!/usr/bin/env python3
"""Gzip every file under a web/ directory into one C header for ESP32 firmware.

Standalone:
    python3 embed_web.py --src web --out include/web_assets.h [--target idf] [--budget 80]

PlatformIO (platformio.ini):
    extra_scripts = pre:tools/embed_web.py      ; uses <project>/web -> include/web_assets.h

The header defines WEB_ASSETS[] = {path, mime, data, size}; serve each entry with
"Content-Encoding: gzip". "/index.html" is also registered as "/".
Output is deterministic (mtime=0, sorted), so unchanged sources don't trigger rebuilds.
"""
import argparse
import gzip
import sys
from pathlib import Path

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
}


def generate(src: Path, out: Path, target: str = "arduino", budget_kb: float = 0) -> int:
    files = [p for p in sorted(src.rglob("*")) if p.is_file() and p.suffix.lower() in TYPES]
    if not files:
        raise SystemExit(f"embed_web: no web files found in {src}")
    progmem = " PROGMEM" if target == "arduino" else ""
    include = "#include <Arduino.h>" if target == "arduino" else "#include <stddef.h>\n#include <stdint.h>"
    parts = [f"// Generated by embed_web.py from {src.name}/. Do not edit.\n#pragma once\n{include}\n\n"]
    entries, total_raw, total_gz = [], 0, 0
    report = []
    for i, path in enumerate(files):
        raw = path.read_bytes()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        total_raw += len(raw)
        total_gz += len(data)
        name = f"web_asset_{i}"
        route = "/" + path.relative_to(src).as_posix()
        report.append(f"  {route:<32} {len(raw):>8} -> {len(data):>7} B")
        parts.append(f"// {route}\nstatic const uint8_t {name}[]{progmem} = {{\n")
        parts.extend(",".join(str(b) for b in data[j : j + 24]) + ",\n" for j in range(0, len(data), 24))
        parts.append("};\n")
        mime = TYPES[path.suffix.lower()]
        entries.append(f'    {{"{route}", "{mime}", {name}, sizeof({name})}}')
        if route == "/index.html":
            entries.append(f'    {{"/", "{mime}", {name}, sizeof({name})}}')
    parts.append("\ntypedef struct WebAsset {\n    const char *path;\n    const char *type;\n    const uint8_t *data;\n    size_t size;\n} WebAsset;\n")
    parts.append("static const WebAsset WEB_ASSETS[] = {\n" + ",\n".join(entries) + "\n};\n")
    parts.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);\n")
    content = "".join(parts)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != content:
        out.write_text(content)
    print("embed_web: " + str(out))
    print("\n".join(report))
    print(f"  {'total':<32} {total_raw:>8} -> {total_gz:>7} B")
    if budget_kb and total_gz > budget_kb * 1024:
        print(f"embed_web: gzip total {total_gz / 1024:.1f} KB exceeds budget {budget_kb} KB", file=sys.stderr)
        return 1
    return 0


if "Import" in globals():  # PlatformIO pre-script
    Import("env")  # noqa: F821
    root = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    generate(root / "web", root / "include" / "web_assets.h")
elif __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", type=Path, default=Path("web"))
    ap.add_argument("--out", type=Path, default=Path("include/web_assets.h"))
    ap.add_argument("--target", choices=["arduino", "idf"], default="arduino")
    ap.add_argument("--budget", type=float, default=0, help="fail if total gzip size exceeds this many KB")
    a = ap.parse_args()
    sys.exit(generate(a.src.resolve(), a.out.resolve(), a.target, a.budget))
